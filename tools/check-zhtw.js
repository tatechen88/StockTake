// 允许出现的例外（角色名等用户数据、命令字面量）
const ALLOW_CHARS = new Set([]);

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error('usage: node tools/check-zhtw.js <file...>');
  process.exit(2);
}

let total = 0;
for (const f of files) {
  let text = fs.readFileSync(f, 'utf8');
  const name = f.split(/[\\/]/).pop();
  let scope = '全文';
  // Lua 文件里三语共存（zhCN/zhTW/enUS 三张表 + 中文注释），只检查 zhTW 区块
  if (/\.lua$/i.test(f)) {
    const start = text.indexOf('local zhTW = {');
    if (start === -1) {
      console.log('SKIP ' + name + '（未找到 local zhTW 区块，跳过）');
      continue;
    }
    const rest = text.slice(start);
    const endIdx = rest.indexOf('\n}');
    text = endIdx === -1 ? rest : rest.slice(0, endIdx);
    scope = 'local zhTW 区块';
  }
  const lines = text.split(/\r?\n/);
  const hits = [];
  lines.forEach((line, i) => {
    for (const ch of line) {
      if (CN2TW[ch] && !ALLOW_CHARS.has(ch)) hits.push({ line: i + 1, ch, tw: CN2TW[ch], text: line.trim().slice(0, 70) });
    }
  });
  if (hits.length === 0) {
    console.log('OK   ' + name + '  (' + scope + ')');
  } else {
    console.log('FAIL ' + name + '  (' + scope + '，' + hits.length + ' 处简体字)');
    for (const h of hits.slice(0, 40)) console.log('   L' + h.line + '  ' + h.ch + ' → ' + h.tw + '   | ' + h.text);
    if (hits.length > 40) console.log('   … 其余 ' + (hits.length - 40) + ' 处省略');
    total += hits.length;
  }
}
console.log('\n合计命中（简体字出现在繁体内容里）：' + total);
process.exit(total === 0 ? 0 : 1);
